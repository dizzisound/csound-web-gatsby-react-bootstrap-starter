import React from "react"
import { Row, Col } from "react-bootstrap"
import Fader from "./fader"
import Knob from "./knob"
import Switch from "./switch"
import TabPanel from "./tabpanel"
import NumberInput from "./numberinput"
import Toggle from "./toggle"
import Adsr from "./adsr"
import XYPad from "./xy"
import PanelSwitch from "./panelswitch"
import Scope from "./scope"

class Panel extends React.Component {

  constructor(props) {
    super(props)
    this.state = { on: false }
    this.props.def.changeValue = this.setValue.bind(this)
  }

  handleClick() {
    this.props.onChange(this.props.def.id, (!this.state.on) ? 1 : 0)
    this.setState({ on: !this.state.on })
  }

  componentDidMount() {
  }

  onChange(id, val) {
    this.props.onChange(id, val)
  }

  setValue(on) {
    this.setState({ on: on })
    this.props.onChange(this.props.def.id, on)
  }

  render() {
    const components = []
    if (this.props.def.type === "multifader") {
      // the fader definitions are generated by Instrument (multifaderWidgets)
      this.props.def.widgets.forEach((itm) => {
        components.push(
          <Fader def={itm} key={itm.id} onChange={this.onChange.bind(this)} />,
        )
      })
    } else {
      this.props.def.widgets.forEach((component) => {
        switch (component.type) {
          case "panel" :
          case "multifader":
            components.push(
              <Panel label={component.label} def={component} key={component.id} onChange={this.onChange.bind(this)} />,
            )
            break
          case "tabpanel" :
            components.push(
              <TabPanel label={component.label} def={component} key={component.id}
                        onChange={this.onChange.bind(this)} />,
            )
            break
          case "fader":
            components.push(
              <Fader def={component} key={component.id} onChange={this.onChange.bind(this)} />,
            )
            break
          case "knob":
            components.push(
              <Knob def={component} key={component.id}
                    onChange={this.onChange.bind(this)} />,
            )
            break
          case "toggle":
            components.push(
              <Toggle def={component} key={component.id} onChange={this.onChange.bind(this)} />,
            )
            break
          case "select":
            components.push(
              <Switch def={component} key={component.id} onChange={this.onChange.bind(this)}
                      vertical={component.vertical} />,
            )
            break
          case "spinner":
            components.push(
              <NumberInput def={component} key={component.id}
                           onChange={this.onChange.bind(this)} />,
            )
            break
          case "xy":
            components.push(
              <XYPad def={component} key={component.id} onChange={this.onChange.bind(this)} />,
            )
            break
          case "adsr":
            components.push(
              <Adsr def={component} key={component.id} onChange={this.onChange.bind(this)}/>
            )
            break;
          case "scope":
            components.push(
              <Scope def={component} key={component.id} />
            )
            break
          default:
            if (component.func) {
              let comp = component.func(component, this.onChange.bind(this))
              components.push(comp)
            }
            break
        }
      })
    }
    let rcomp = components
    if (this.props.def.vertical) {
      rcomp = (
        <Col className="patvertical">
          {components.map((c,i) => (
              <Row className="g-0" key={"v"+i}>{c}</Row>
          )
          )}
        </Col>
      )
    }
    let label = this.props.label
    if (this.props.def.on) {
      label = <PanelSwitch label={this.props.label} on={this.state.on} onClick={this.handleClick.bind(this)} />
    }
    if (this.props.label) {
      return (
        <Col className="patcol">
          <Row className="g-0"><Col className="patlabel">{label}</Col></Row>
          <Row className="g-0 patbody" style={{ flexWrap: this.props.def.wrap ? "wrap" : "nowrap" }}>
            {rcomp}
          </Row>
        </Col>
      )
    } else {
      return (
        <Col className="patcol" md={"auto"}>
          <Row className="g-0 patbody" style={{ flexWrap: this.props.def.wrap ? "wrap" : "nowrap" }}>
            {rcomp}
          </Row>
        </Col>
      )
    }
  }
}

export default Panel
